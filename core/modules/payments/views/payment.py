from drf_spectacular.utils import extend_schema
from rest_framework import status
from rest_framework.exceptions import APIException
from rest_framework.generics import ListAPIView
from rest_framework.permissions import AllowAny, IsAuthenticated
from rest_framework.response import Response
from rest_framework.views import APIView

from core.modules.payments.models.payment import Payment
from core.modules.payments.serializers.payment import (
    CardPaymentResponseSerializer,
    PaymentCardCreateSerializer,
    PaymentPixCreateSerializer,
    PaymentSerializer,
    PixPaymentResponseSerializer,
)
from core.modules.payments.services.payment import PaymentService

PAYMENT_NOTIFICATION_URL = "https://3009.michalski.app/api/v1/payments/webhook/"


@extend_schema(tags=["Pagamentos"])
class PaymentPixListCreateView(ListAPIView):
    permission_classes = [IsAuthenticated]
    serializer_class = PaymentSerializer

    def get_queryset(self):
        PaymentService.sync_pending_for_user(self.request.user)
        return Payment.objects.filter(user=self.request.user)

    @extend_schema(summary="List my payments")
    def get(self, request, *args, **kwargs):
        return super().get(request, *args, **kwargs)

    @extend_schema(
        summary="Create a fixed-price Mercado Pago PIX payment",
        description="Generates a R$ 9.99 PIX QR Code with payer CPF and full name.",
        request=PaymentPixCreateSerializer,
        responses={201: PixPaymentResponseSerializer},
    )
    def post(self, request):
        serializer = PaymentPixCreateSerializer(data=request.data)
        serializer.is_valid(raise_exception=True)

        result = PaymentService.create_pix_payment(
            user=request.user,
            title=serializer.validated_data["title"],
            cpf=serializer.validated_data["cpf"],
            name=serializer.validated_data["name"],
            notification_url=PAYMENT_NOTIFICATION_URL,
        )
        return Response(result, status.HTTP_201_CREATED)


@extend_schema(tags=["Pagamentos"])
class PaymentCardCreateView(APIView):
    permission_classes = [IsAuthenticated]

    @extend_schema(
        summary="Create a fixed-price Mercado Pago card payment",
        description="Charges R$ 9.99 using a one-time card token generated by MercadoPago.js.",
        request=PaymentCardCreateSerializer,
        responses={201: CardPaymentResponseSerializer},
    )
    def post(self, request):
        serializer = PaymentCardCreateSerializer(data=request.data)
        serializer.is_valid(raise_exception=True)

        result = PaymentService.create_card_payment(
            user=request.user,
            title=serializer.validated_data["title"],
            cpf=serializer.validated_data["cpf"],
            email=serializer.validated_data["email"],
            token=serializer.validated_data["token"],
            installments=serializer.validated_data["installments"],
            payment_method_id=serializer.validated_data["payment_method_id"],
            issuer_id=serializer.validated_data.get("issuer_id"),
            notification_url=PAYMENT_NOTIFICATION_URL,
        )
        return Response(result, status.HTTP_201_CREATED)


class PaymentWebhookView(APIView):
    authentication_classes = []
    permission_classes = [AllowAny]

    @extend_schema(summary="Mercado Pago webhook", request=None, responses={200: None})
    def post(self, request):
        topic = request.data.get("type") or request.query_params.get("type")
        provider_payment_id = request.data.get("data", {}).get(
            "id"
        ) or request.query_params.get("data.id")
        if topic == "payment" and provider_payment_id:
            try:
                PaymentService.sync_from_provider(str(provider_payment_id))
            except APIException:
                # Mercado Pago retries webhooks. A manual status refresh can also
                # reconcile the payment if this attempt fails.
                pass
        # Always return 200, otherwise Mercado Pago keeps retrying.
        return Response(status=status.HTTP_200_OK)


# Backward-compatible class name used by the original URL configuration.
PaymentListCreateView = PaymentPixListCreateView
