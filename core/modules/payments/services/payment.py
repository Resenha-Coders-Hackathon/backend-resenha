import os
import re
from decimal import Decimal

import mercadopago
from rest_framework import exceptions

from core.modules.payments.models.payment import Payment
from core.modules.payments.response_messages import MSG_PAYMENT_PROVIDER_UNAVAILABLE

MP_ACCESS_TOKEN = os.getenv("MP_ACCESS_TOKEN", "")
PAYMENT_AMOUNT = Decimal("9.99")


def _sdk() -> mercadopago.SDK:
    return mercadopago.SDK(MP_ACCESS_TOKEN)


class PaymentService:
    @staticmethod
    def _create_local_payment(user, title: str, cpf: str, name: str = "") -> Payment:
        return Payment.objects.create(
            user=user,
            title=title,
            amount=PAYMENT_AMOUNT,
            payer_cpf=re.sub(r"\D", "", cpf),
            payer_name=name.strip(),
        )

    @staticmethod
    def _request_options(payment: Payment) -> mercadopago.config.RequestOptions:
        request_options = mercadopago.config.RequestOptions()
        request_options.custom_headers = {"x-idempotency-key": str(payment.id)}
        return request_options

    @staticmethod
    def _create_at_provider(payment: Payment, payload: dict) -> dict:
        try:
            result = (
                _sdk()
                .payment()
                .create(payload, PaymentService._request_options(payment))
            )
        except Exception as error:
            payment.delete()
            raise exceptions.APIException(MSG_PAYMENT_PROVIDER_UNAVAILABLE) from error

        if result.get("status") not in (200, 201):
            payment.delete()
            raise exceptions.APIException(MSG_PAYMENT_PROVIDER_UNAVAILABLE)
        return result.get("response", {})

    @staticmethod
    def create_pix_payment(
        user, title: str, cpf: str, name: str, notification_url: str
    ) -> dict:
        """Create a local payment and generate a Mercado Pago PIX charge."""
        payment = PaymentService._create_local_payment(user, title, cpf, name)
        parts = payment.payer_name.split(" ", 1)
        first_name = parts[0]
        last_name = parts[1] if len(parts) > 1 else first_name

        payload = {
            "transaction_amount": float(PAYMENT_AMOUNT),
            "description": title,
            "payment_method_id": "pix",
            "payer": {
                "email": user.email,
                "first_name": first_name,
                "last_name": last_name,
                "identification": {
                    "type": "CPF",
                    "number": payment.payer_cpf,
                },
            },
            "external_reference": str(payment.id),
            "notification_url": notification_url,
        }

        data = PaymentService._create_at_provider(payment, payload)
        tx_data = data.get("point_of_interaction", {}).get("transaction_data", {})

        payment.provider_payment_id = str(data.get("id", ""))
        payment.status = data.get("status", Payment.Status.PENDING)
        payment.qr_code = tx_data.get("qr_code", "")
        payment.qr_code_base64 = tx_data.get("qr_code_base64", "")
        payment.ticket_url = tx_data.get("ticket_url", "")
        payment.save(
            update_fields=[
                "provider_payment_id",
                "status",
                "qr_code",
                "qr_code_base64",
                "ticket_url",
                "updated_at",
            ]
        )

        return {
            "payment_id": payment.id,
            "status": payment.status,
            "qr_code": payment.qr_code,
            "qr_code_base64": payment.qr_code_base64,
            "ticket_url": payment.ticket_url,
        }

    @staticmethod
    def create_card_payment(
        user,
        title: str,
        cpf: str,
        email: str,
        token: str,
        installments: int,
        payment_method_id: str,
        issuer_id: int | None,
        notification_url: str,
    ) -> dict:
        """Create a card payment using a one-time token generated by MercadoPago.js."""
        payment = PaymentService._create_local_payment(user, title, cpf)

        payload = {
            "transaction_amount": float(PAYMENT_AMOUNT),
            "token": token,
            "description": title,
            "installments": installments,
            "payment_method_id": payment_method_id,
            "payer": {
                "email": email,
                "identification": {
                    "type": "CPF",
                    "number": payment.payer_cpf,
                },
            },
            "external_reference": str(payment.id),
            "notification_url": notification_url,
        }
        if issuer_id is not None:
            payload["issuer_id"] = issuer_id

        data = PaymentService._create_at_provider(payment, payload)
        payment.provider_payment_id = str(data.get("id", ""))
        payment.status = data.get("status", Payment.Status.PENDING)
        payment.save(update_fields=["provider_payment_id", "status", "updated_at"])

        return {
            "payment_id": payment.id,
            "status": payment.status,
            "status_detail": data.get("status_detail", ""),
        }

    # Backward compatibility alias
    create_checkout = create_pix_payment

    @staticmethod
    def sync_payment(payment: Payment) -> bool:
        """Refresh one local payment using the authoritative provider response."""
        if not payment.provider_payment_id:
            return False

        try:
            result = _sdk().payment().get(payment.provider_payment_id)
        except Exception as error:
            raise exceptions.APIException(MSG_PAYMENT_PROVIDER_UNAVAILABLE) from error

        if result.get("status") != 200:
            raise exceptions.APIException(MSG_PAYMENT_PROVIDER_UNAVAILABLE)

        data = result.get("response", {})
        if (
            str(data.get("id", "")) != payment.provider_payment_id
            or str(data.get("external_reference", "")) != str(payment.id)
            or data.get("status") not in Payment.Status.values
        ):
            return False

        payment.status = data["status"]
        payment.save(update_fields=["status", "updated_at"])
        return True

    @staticmethod
    def sync_pending_for_user(user) -> None:
        pending = Payment.objects.filter(
            user=user,
            status__in=(Payment.Status.PENDING, Payment.Status.IN_PROCESS),
        ).exclude(provider_payment_id="")
        for payment in pending:
            PaymentService.sync_payment(payment)

    @staticmethod
    def sync_from_provider(provider_payment_id: str) -> bool:
        """Resolve a webhook ID locally, then verify it against Mercado Pago."""
        payment = Payment.objects.filter(
            provider_payment_id=provider_payment_id
        ).first()
        if payment is None:
            return False
        return PaymentService.sync_payment(payment)
